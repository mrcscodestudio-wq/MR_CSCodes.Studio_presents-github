// Arithmetic operations in C

#include <stdio.h>

int main(){

     int a = 8;
     int b = 19;

     printf("%d\n",a + b);
     printf("%d\n",a - b);
     printf("%d\n",a * b);
     printf("%d\n",a % b);
     printf("%d\n",a / b);

     float c = 66.77;
     float d = 124.56;

     printf("%f\n",c + d);
     printf("%f\n",c - d);
     printf("%f\n",c * d);
     printf("%f\n",c / d);

     

    return 0;
}
